import { readdirSync, writeFileSync } from 'node:fs';

const rows = [];
function add(dir, keyPrefix) {
  for (const name of readdirSync(new URL(`../assets/sample/${dir}/`, import.meta.url))) {
    if (name.startsWith('.')) continue;
    const key = `${keyPrefix}${name}`;
    rows.push(`  ${JSON.stringify(key)}: require('../../assets/sample/${dir}/${name}'),`);
  }
}
add('img', 'img/');
add('media', 'media/');
rows.sort();
const body = `// Generated by scripts/gen-media.mjs. Do not edit.
export const sampleMedia = {
${rows.join('\n')}
} as const;

export type SampleMediaKey = keyof typeof sampleMedia;
`;
writeFileSync(new URL('../src/mocks/media.ts', import.meta.url), body);
