import { readFileSync, writeFileSync } from 'node:fs';
import prettier from 'prettier';

const outputPath = new URL('../src/theme/tokens.ts', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const source = `// Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit.
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;
`;
const config = await prettier.resolveConfig(outputPath);
const body = await prettier.format(source, { ...config, parser: 'typescript' });
writeFileSync(outputPath, body);
